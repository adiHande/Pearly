// Difficulty availability
function updateDifficultyOptions(){
    for (
        const option of
        difficultySelect.options
    ){
        const deck =
            gameDecks[
                currentTheme
            ][
                option.value
            ];

        const needed =
            difficultySettings[
                option.value
            ].pairs;

        option.disabled =
            deck.length < needed;
    }

    if (
        difficultySelect
            .selectedOptions[0]
            .disabled
    ){
        const available =
            [...difficultySelect.options]
                .find(
                    option =>
                        !option.disabled
                );

        if (available){
            difficultySelect.value =
                available.value;
        }
    }
}


