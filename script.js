// Wait helper
function wait(ms){
    return new Promise(
        resolve =>
            setTimeout(resolve, ms)
    );
}


// Shuffle
function shuffle(array){
    for (
        let i = array.length - 1;
        i > 0;
        i--
    ){
        const j =
            Math.floor(
                Math.random() * (i + 1)
            );

        [array[i], array[j]] =
            [array[j], array[i]];
    }

    return array;
}


// Regular one-shot sound
function playSound(name){
    if (!soundEnabled){
        return null;
    }

    const sound =
        new Audio(audioPaths[name]);

    sound
        .play()
        .catch(() => {});

    return sound;
}


// Win / lose sound
function playResultSound(name){
    if (!soundEnabled){
        return;
    }

    stopResultSound();

    resultSound =
        new Audio(audioPaths[name]);

    resultSound
        .play()
        .catch(() => {});

    resultSound.addEventListener(
        "ended",
        () =>{
            resultSound = null;
        },
        { once: true }
    );
}


// Stop currently playing win/lose audio
function stopResultSound(){
    if (!resultSound){
        return;
    }

    resultSound.pause();

    resultSound.currentTime = 0;

    resultSound = null;
}


// Clear any delayed result audio/popup
