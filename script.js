// Finish game
function finishGame(won){
    if (gameOver){
        return;
    }

    gameOver =
        true;

    boardLocked =
        true;

    clearInterval(timer);

    stopResultFeedback();


    bestTimeBox
        .classList
        .toggle(
            "hidden",
            currentTimerMode ===
            "relaxed"
        );


    if (won){

        const scores =
            updateBestScores();

        resultTitle.textContent =
            "You won!";


        if (
            currentTimerMode ===
            "relaxed"
        ){
            resultMessage.textContent =
                `You matched every pair in ${moves} moves!`;

            bestTimeText.textContent =
                "--";
        }

        else{
            resultMessage.textContent =
                `You matched every pair in ${moves} moves and ${seconds} seconds!`;

            bestTimeText.textContent =
                scores.bestTime
                    ? `${scores.bestTime}s`
                    : "--";
        }


        bestMovesText.textContent =
            scores.bestMoves ??
            "--";
    }


    else{

        resultTitle.textContent =
            "Time's up!";

        resultMessage.textContent =
            `You matched ${matchedPairs} of ${difficultySettings[currentDifficulty].pairs} pairs.`;

        const scores =
            getBestScores(
                currentDifficulty
            );

        bestTimeBox
            .classList
            .remove("hidden");

        bestMovesText.textContent =
            scores.bestMoves ??
            "--";

        bestTimeText.textContent =
            scores.bestTime
                ? `${scores.bestTime}s`
                : "--";
    }


    const resultSoundName =
        won
            ? "win"
            : "lose";


    // ==============================================
    // VERSION A
    //
    // Win/Lose sound plays FIRST.
    // One second later:
    // result popup + popup sound.
    // ==============================================

    if (
        soundTest.resultSoundOrder ===
        "before"
    ){
        playResultSound(
            resultSoundName
        );


        if (soundEnabled){
            resultPopupTimeout =
                setTimeout(
                    () =>{
                        openResultPopup();

                        resultPopupTimeout =
                            null;
                    },
                    1000
                );
        }

        else{
            openResultPopup();
        }

        return;
    }


    // ==============================================
    // VERSION B
    //
    // Result popup + popup sound FIRST.
    // Tiny pause.
    // Then Win/Lose sound.
    // ==============================================

    openResultPopup();


    if (soundEnabled){
        resultSoundTimeout =
            setTimeout(
                () =>{
                    playResultSound(
                        resultSoundName
                    );

                    resultSoundTimeout =
                        null;
                },
                180
            );
    }
}


// Synchronize toggles
function syncAudioToggles(){
    soundToggle.checked =
        soundEnabled;

    dialogSoundToggle.checked =
        soundEnabled;
}


// Save sound setting
function saveAudioSettings(){
    localStorage.setItem(
        "soundEnabled",
        soundEnabled
    );

    syncAudioToggles();
}


// Toggle sound
function handleSoundToggle(toggle){
    const turningOn =
        toggle.checked;


    if (turningOn){

        soundEnabled =
            true;

        saveAudioSettings();


        playSound(
            "toggleOn"
        );


        if (
            !homeScreen
                .classList
                .contains("hidden")
        ){
            startHomeLoop();
        }
    }


    else{

        // Must play BEFORE disabling sound.
        playSound(
            "toggleOff"
        );


        soundEnabled =
            false;

        saveAudioSettings();


        stopHomeLoop();

        stopResultSound();

        clearResultTimers();
    }
}


